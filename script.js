(function initDesignerStack() {
  const stack = document.querySelector('.designer-stack');
  if (!stack) return;
  const imgs = [...stack.querySelectorAll('.designer-stack-img')];
  const n = imgs.length;
  let active = 0;
  let timer;

  const update = () => {
    imgs.forEach((img, i) => {
      const offset = (i - active + n) % n;
      if (offset === 0) {
        img.dataset.dsPos = 'center';
        img.style.zIndex = '3';
      } else if (offset === 1) {
        img.dataset.dsPos = 'right';
        img.style.zIndex = '2';
      } else if (offset === n - 1) {
        img.dataset.dsPos = 'left';
        img.style.zIndex = '2';
      } else {
        img.dataset.dsPos = 'hidden';
        img.style.zIndex = '1';
      }
    });
  };

  const startTimer = () => {
    clearInterval(timer);
    timer = setInterval(() => { active = (active + 1) % n; update(); }, 4500);
  };

  stack.querySelector('.designer-stack-prev').addEventListener('click', () => {
    active = (active - 1 + n) % n;
    update();
    startTimer();
  });
  stack.querySelector('.designer-stack-next').addEventListener('click', () => {
    active = (active + 1) % n;
    update();
    startTimer();
  });

  stack.addEventListener('mouseenter', () => clearInterval(timer));
  stack.addEventListener('mouseleave', startTimer);

  update();
  startTimer();
})();

