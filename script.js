let currentLang = localStorage.getItem('marrolo-lang') || 'en';

const t = (key) => (translations[currentLang] || translations.en)[key] || key;

const applyLanguage = () => {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = (translations[currentLang] || translations.en)[key];
    if (val !== undefined) el.textContent = val;
  });
  document.querySelectorAll('[data-lang-toggle]').forEach((btn) => {
    btn.setAttribute('aria-label', t('aria.lang'));
  });
  document.querySelectorAll('.lang-opt').forEach((opt) => {
    opt.classList.toggle('is-active', opt.dataset.lang === currentLang);
  });
};

